-- Buat Database
IF NOT EXISTS (SELECT name FROM master.dbo.sysdatabases WHERE name = N'DX_LMS')
BEGIN
    CREATE DATABASE [DX_LMS];
END
GO

USE [DX_LMS];
GO

-- =========================================================================================
-- TABLE: DX_LMS_M_Employees
-- =========================================================================================
IF NOT EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[DX_LMS_M_Employees]') AND type in (N'U'))
BEGIN
    CREATE TABLE [dbo].[DX_LMS_M_Employees] (
        [employee_id] BIGINT IDENTITY(1,1) PRIMARY KEY,
        [npk] VARCHAR(50) NOT NULL UNIQUE,
        [fullname] VARCHAR(150) NOT NULL,
        [email] VARCHAR(150) NOT NULL UNIQUE,
        [password] VARCHAR(255) NOT NULL,
        [golongan] VARCHAR(50) NOT NULL,
        [jabatan] VARCHAR(100) NOT NULL,
        [bu_code] INT NOT NULL,
        [section] VARCHAR(150) NOT NULL,
        [department] VARCHAR(150) NOT NULL,
        [division] VARCHAR(150) NOT NULL,
        [directorate] VARCHAR(150) NOT NULL,
        [role] VARCHAR(50) NOT NULL, -- e.g., 'student', 'teacher', 'admin'
        [status] VARCHAR(50) NOT NULL DEFAULT 'Active',
        [created_at] DATETIME2 DEFAULT CURRENT_TIMESTAMP,
        [updated_at] DATETIME2 DEFAULT CURRENT_TIMESTAMP,
        [created_by] BIGINT NULL,
        [updated_by] BIGINT NULL
    );
END
GO

